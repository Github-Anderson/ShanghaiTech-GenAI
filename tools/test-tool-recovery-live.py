#!/usr/bin/env python3
"""Opt-in non-GPT probes. Every created upstream conversation is deleted.

Run inside the deployed gateway container with this synced script on stdin.
Commands generated by models are inspected only; synthetic observations are
explicitly labelled. Credentials are read from the existing gateway settings.
"""
import asyncio
import copy
import json
import uuid
from unittest.mock import patch

import httpx

from gateway.app import Service, delete_conversations
from gateway.conversations import Conversations
from gateway.protocol import GatewayError, build_upstream_payload
from gateway.settings import load_settings
from gateway.site_api import signed_get
from gateway.tool_bridge import ToolBridge
from gateway.upstream import stream_upstream

TOOLS = [{'type': 'function', 'function': {'name': 'bash', 'description': 'Request a shell command from the client.',
    'parameters': {'type': 'object', 'properties': {'description': {'type': 'string'}, 'command': {'type': 'string'}},
                   'required': ['description', 'command'], 'additionalProperties': False}}}]
MODELS = ('deepseek-pro', 'Kimi-k3', 'qwen-instruct', 'chatglm')
BROKEN = '{"type":"tool_calls","tool_calls":[{"name":"bash","arguments":{"description":"Read a marker","command":"printf RECOVERY_MARKER","call_id":"call_11"}]}'
BAD_SCHEMA = '{"type":"tool_calls","tool_calls":[{"name":"bash","arguments":{"description":"Read a marker","command":"printf RECOVERY_MARKER","call_id":"call_11"}}]}'


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def report(**row):
    print(json.dumps(row, ensure_ascii=False), flush=True)


async def history_empty(service, groups):
    token = service.credentials.get_token()
    signing = service.credentials.get_signing(token)
    for group in groups:
        data = await signed_get(service.client, '/htk/ai/history/getByChatGroupId',
                                {'chatGroupId': group}, token, signing)
        require(data.get('result') in (None, []), 'Test history remains after deletion')


async def chat(client, headers, body):
    async with client.stream('POST', 'http://127.0.0.1:8000/v1/chat/completions', headers=headers, json=body) as response:
        if response.status_code != 200:
            data = json.loads(await response.aread())
            raise RuntimeError('gateway_http_' + str(response.status_code) + ':' + data.get('error', {}).get('code', 'unknown'))
        if not body.get('stream'):
            result = json.loads(await response.aread())
            return result['choices'][0]['message'], result['choices'][0]['finish_reason']
        parts, calls, finish, done = [], [], None, False
        async for line in response.aiter_lines():
            if not line.startswith('data: '):
                continue
            if line == 'data: [DONE]':
                done = True
                continue
            event = json.loads(line[6:])
            if 'error' in event:
                raise RuntimeError(event['error']['code'])
            for choice in event.get('choices', []):
                delta = choice.get('delta', {})
                parts.append(delta.get('content') or '')
                calls.extend({k: v for k, v in call.items() if k != 'index'} for call in delta.get('tool_calls', []))
                finish = choice.get('finish_reason') or finish
        require(done and finish in ('stop', 'tool_calls'), 'Incomplete SSE response')
        return {'role': 'assistant', 'content': ''.join(parts), **({'tool_calls': calls} if calls else {})}, finish


async def gateway_case(service, client, headers, model, chain=False):
    local_id = 'format-regression-' + uuid.uuid4().hex
    try:
        messages = [{'role': 'user', 'content': '这是协议回归测试。请原样输出以下两行，不调用工具：\n'
                     'osascript -e \'quit app "Example"\'\nC:\\temp\\new\\file.txt'}]
        request = {'model': model, 'tools': TOOLS, 'conversation_id': local_id, 'max_tokens': 2048,
                   'messages': messages, 'stream': True, 'shanghaitech': {'search': False, 'thinking': False}}
        answer, reason = await chat(client, headers, request)
        require(reason == 'stop' and not answer.get('tool_calls'), 'Literal answer attempted a tool')
        require('quit app "Example"' in answer['content'] and 'C:\\temp\\new\\file.txt' in answer['content'],
                'Quoted command or literal path was changed')
        report(case='literal_stream', model=model, status='PASS')
        messages.append(answer)
        for index in range(12 if chain else 1):
            marker = 'PROBE_MARKER_' + str(index)
            messages.append({'role': 'user', 'content':
                '协议测试：请使用 bash 工具请求执行 printf 打印 ' + marker +
                '。这是测试客户端，工具执行由客户端负责；你只需生成调用，不要模拟结果。'})
            request.update(stream=index % 2 == 0, tool_choice='required')
            answer, reason = await chat(client, headers, request)
            require(reason == 'tool_calls' and len(answer.get('tool_calls', [])) == 1, 'Expected exactly one tool call')
            call = answer['tool_calls'][0]
            args = json.loads(call['function']['arguments'])
            require(call['function']['name'] == 'bash' and marker in args['command'], 'Wrong tool or marker')
            require(set(args) == {'description', 'command'}, 'Unexpected argument fields')
            messages.extend([answer, {'role': 'tool', 'tool_call_id': call['id'],
                'content': 'Synthetic test observation (the command was NOT executed): ' + marker}])
            report(case='tool_roundtrip', model=model, step=index + 1, status='PASS')
        messages.append({'role': 'user', 'content': '测试结束。仅回复 TEST_COMPLETE，不再调用工具。'})
        request.update(stream=False, tool_choice='none')
        answer, reason = await chat(client, headers, request)
        require(reason == 'stop' and 'TEST_COMPLETE' in answer['content'], 'Follow-up answer failed')
        report(case='final_nonstream', model=model, status='PASS')
    finally:
        journal = Conversations(service.conversations.path)
        token = service.credentials.get_token()
        groups = journal.deletion_plan(token, [local_id]) if any(k[2] == local_id for k in journal.history.values()) else []
        response = await client.delete('http://127.0.0.1:8000/v1/conversations/' + local_id, headers=headers)
        require(response.status_code == 200 and response.json().get('deleted'), 'Gateway test conversation deletion failed')
        await history_empty(service, groups)
        remaining = Conversations(service.conversations.path)
        require(not any(k[2] == local_id for k in remaining.history.values()), 'Test mapping was retained')
        report(case='cleanup', model=model, session=local_id, deleted_groups=len(groups), website_history_empty=True, status='PASS')


async def fault_case(settings, client, raw, label, model='deepseek-pro'):
    service = Service(settings, client)
    # Independent in-memory mappings prevent a second process from overwriting
    # the running gateway's durable journal. All known groups are deleted below.
    service.conversations = Conversations()
    local_id = 'format-correction-' + uuid.uuid4().hex
    request = {'model': model, 'tools': TOOLS, 'tool_choice': 'required', 'max_tokens': 2048,
               'messages': [{'role': 'user', 'content':
                   '协议测试：使用 bash 工具请求 printf 打印 RECOVERY_MARKER。只生成调用，不要模拟执行。'}],
               'shanghaitech': {'search': False, 'thinking': False}}
    bridge = ToolBridge(request)
    payload, _ = build_upstream_payload(bridge.rewrite(request), settings.models)
    attempts, upstream_calls = [], []
    async def injected(client, payload, root, token, **kwargs):
        attempts.append(copy.deepcopy(payload))
        if len(attempts) == 1:
            yield {'content': raw}
            yield {'finish_reason': 'stop'}
        else:
            upstream_calls.append(True)
            async for event in stream_upstream(client, payload, root, token, **kwargs):
                yield event
    try:
        with patch('gateway.app.stream_upstream', injected):
            events = [event async for event in service.events(payload, settings.models[model]['root_ai_type'],
                       public_model=model, conversation_id=local_id, bridge=bridge)]
        require(len(attempts) == 2 and len(upstream_calls) == 1, 'Expected one real correction request')
        calls = [call for event in events for call in event.get('tool_calls', [])]
        require(len(calls) == 1, 'Correction did not emit exactly one tool')
        args = json.loads(calls[0]['function']['arguments'])
        require(calls[0]['function']['name'] == 'bash' and 'RECOVERY_MARKER' in args['command'], 'Correction changed tool or marker')
        require(set(args) == {'description', 'command'}, 'Correction retained invalid fields')
        require(attempts[0]['chatGroupId'] == attempts[1]['chatGroupId'], 'Correction changed conversation')
        report(case=label, model=model, injected_failures=1, real_correction_calls=1, commands_executed=0, status='PASS')
    finally:
        groups = list(service.conversations.history)
        if groups:
            deleted = await delete_conversations(service, [local_id])
            require(deleted['deleted'] and not service.conversations.history, 'Fault-test deletion failed')
            await history_empty(service, groups)
        report(case='cleanup', model=model, session=local_id, deleted_groups=len(groups), website_history_empty=True, status='PASS')


async def main():
    settings = load_settings()
    key = settings.gateway_key_file.read_text().strip()
    headers = {'Authorization': 'Bearer ' + key}
    failures = []
    async with httpx.AsyncClient(timeout=330, trust_env=False, follow_redirects=False) as client:
        service = Service(settings, client)
        for model in MODELS:
            require('gpt' not in model.lower(), 'GPT model is outside test authorization')
            if model not in settings.models:
                continue
            try:
                await gateway_case(service, client, headers, model, chain=model == 'deepseek-pro')
            except Exception as error:
                failures.append(model)
                report(case='gateway_case', model=model, status='FAIL', error_type=type(error).__name__,
                       error_code=error.code if isinstance(error, GatewayError) else str(error)[:160])
        for label, raw in [('missing_brace_live_correction', BROKEN), ('schema_live_correction', BAD_SCHEMA)]:
            try:
                await fault_case(settings, client, raw, label)
            except Exception as error:
                failures.append(label)
                report(case=label, status='FAIL', error_type=type(error).__name__,
                       error_code=error.code if isinstance(error, GatewayError) else str(error)[:160])
    report(case='summary', status='FAIL' if failures else 'PASS', failures=failures, commands_executed=0)
    return bool(failures)


if __name__ == '__main__':
    raise SystemExit(asyncio.run(main()))
